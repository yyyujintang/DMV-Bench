def price_bracket_isolating_pair(
    a: "Variant",
    b: "Variant",
    scope: list["Variant"],
) -> tuple[float, float] | None:
    """Return (low, high) such that **exactly** {a, b} from `scope` have
    `low <= price <= high`. None if no such bracket exists (i.e., another
    `scope` variant has a price strictly between a.price and b.price).

    Bracket boundaries are snapped to ".49" form so they don't accidentally
    coincide with any catalogue price (which use ".99").
    """
    lo_p, hi_p = (a.price, b.price) if a.price <= b.price else (b.price, a.price)
    # Reject if any other product in scope has price ∈ (lo_p, hi_p).
    intruders = [v for v in scope if v.url_hash not in (a.url_hash, b.url_hash)
                 and lo_p < v.price < hi_p]
    if intruders:
        return None
    # Snap the bracket boundaries: low just below a.price, high just above b.price.
    below = sorted([v for v in scope if v.url_hash not in (a.url_hash, b.url_hash)
                    and v.price < lo_p], key=lambda v: v.price)
    above = sorted([v for v in scope if v.url_hash not in (a.url_hash, b.url_hash)
                    and v.price > hi_p], key=lambda v: v.price)
    if below:
        low = (below[-1].price + lo_p) / 2.0
    else:
        low = lo_p - 1.00
    if above:
        high = (hi_p + above[0].price) / 2.0
    else:
        high = hi_p + 1.00
    return (round(low) - 0.51, round(high) - 0.51)


def find_price_adjacent_partner(
    anchor: "Variant",
    candidates: list["Variant"],
    scope: list["Variant"],
) -> "Variant | None":
    """Among `candidates` (must be in `scope`), find one whose price is
    adjacent to `anchor` in `scope` — i.e. there's no third `scope`
    variant whose price lies strictly between anchor and the partner.

    Used to build a tight 2-element bracket containing both anchor and
    partner.
    """
    by_price = sorted(scope, key=lambda v: v.price)
    idx = next((i for i, v in enumerate(by_price) if v.url_hash == anchor.url_hash), -1)
    if idx == -1:
        return None
    neighbours = []
    if idx - 1 >= 0:
        neighbours.append(by_price[idx - 1])
    if idx + 1 < len(by_price):
        neighbours.append(by_price[idx + 1])
    cand_set = {c.url_hash for c in candidates}
    for n in neighbours:
        if n.url_hash in cand_set:
            return n
    return None


def price_cutoff_isolating(target: "Variant", siblings: list["Variant"]) -> float:
    """Pick a "< $X" cut-off such that exactly `target` (and no other sibling
    in the same (cat, tier)) satisfies price < X.

    Uses the price midpoint between target and the next-cheaper sibling
    above it (or 5 cents above target if target is the most expensive).
    """
    # Filter to candidates strictly different from target by urlHash.
    other = [s for s in siblings if s.url_hash != target.url_hash]
    # Among siblings cheaper than target — none should be candidates either,
    # so we need cut-off to exclude them too. Pick X = target.price + 0.50
    # if target is the cheapest; otherwise X = midpoint(target.price, next_above).
    above = sorted([s for s in other if s.price > target.price], key=lambda s: s.price)
    below = [s for s in other if s.price < target.price]
    if below:
        # Below-target siblings would *also* satisfy "< X" unless we phrase
        # the predicate as "<= target.price" or "between L and X". Switch
        # to a between-range predicate in that case.
        return _between_cutoff(target, below, above)
    # No cheaper siblings — simple "< X" works.
    if above:
        x = (target.price + above[0].price) / 2.0
    else:
        x = target.price + 1.00
    return round(x + 0.5) - 0.01  # snap to ".99" form


def _between_cutoff(target, below, above):
    """Helper for the case where there are cheaper siblings; we return a
    single upper bound X but the task generator should pair it with a
    lower bound from `below`'s max price. Caller handles the pair via
    `price_range_isolating()`.

    Returned value is the upper bound only — for backward compat, this
    function is only called when price_range_isolating is desired.
    """
    if above:
        x = (target.price + above[0].price) / 2.0
    else:
        x = target.price + 1.00
    return round(x + 0.5) - 0.01


def price_range_isolating(target: "Variant", siblings: list["Variant"]) -> tuple[float, float]:
    """Return (low, high) such that exactly `target` satisfies low ≤ price ≤ high
    among the (target + siblings) set. Snapped to ".99" boundaries for
    e-commerce feel.
    """
    other = [s for s in siblings if s.url_hash != target.url_hash]
    below = sorted([s for s in other if s.price < target.price], key=lambda s: s.price)
    above = sorted([s for s in other if s.price > target.price], key=lambda s: s.price)
    low = (below[-1].price + target.price) / 2.0 if below else target.price - 1.00
    high = (target.price + above[0].price) / 2.0 if above else target.price + 1.00
    return (round(low + 0.5) - 0.01, round(high + 0.5) - 0.01)
